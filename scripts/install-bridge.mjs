import * as fs from 'node:fs/promises';
import path from 'node:path';
import os from 'node:os';
import { FileQueue, atomicJson } from '../src/queue.mjs';

const root = path.resolve(import.meta.dirname, '..');
const args = process.argv.slice(2);
const option = name => args.includes(name) ? args[args.indexOf(name)+1] : undefined;
const directory = path.resolve(option('--dir') ?? process.env.SV_AGENT_DIR ?? path.join(root,'.sv-agent'));
const scriptsDir = option('--scripts-dir') ?? (process.platform === 'darwin'
  ? path.join(os.homedir(),'Library/Application Support/Dreamtonics/Synthesizer V Studio 2/scripts') : undefined);
await new FileQueue(directory).prepare();
await atomicJson(path.join(directory,'bridge-config.json'), { protocolVersion: 1, pollMs: 50, heartbeatMs: 1000, staleMs: 6000, maxPerTick: 4 });
const luaString = s => JSON.stringify(s.replaceAll('\\','/'));
const loader = `-- Generated by sv-studio-agent. Loads current workspace source on each start.\nfunction getClientInfo()\n  return {name="SV Agent Bridge",author="Local agent bridge",versionNumber=1,minEditorVersion=131072}\nend\nfunction main()\n  local bridge=assert(loadfile(${luaString(path.join(root,'lua/SVAgentBridge.lua'))}))(${luaString(directory)}, ${luaString(path.join(root,'lua'))})\n  bridge.main()\nend\n`;
await fs.writeFile(path.join(directory,'SVAgentBridge.lua'),loader,{ mode: 0o600 });
if (!args.includes('--prepare-only')) {
  if (!scriptsDir) throw new Error('Pass --scripts-dir for your Studio scripts folder on this OS.');
  await fs.mkdir(scriptsDir,{recursive:true});
  const installed = path.join(scriptsDir,'SVAgentBridge.lua');
  const existing = await fs.readFile(installed,'utf8').catch(error => { if(error.code !== 'ENOENT') throw error; return null; });
  if (existing !== null && !existing.startsWith('-- Generated by sv-studio-agent.')) throw new Error(`Refusing to overwrite ${installed}`);
  await fs.writeFile(installed,loader,{mode:0o600});
  console.log(`Installed: ${installed}\nStudio: Scripts → Rescan → SV Agent Bridge`);
}
console.log(JSON.stringify({ mcpServers: { 'synthv-agent': { command: process.execPath, args: [path.join(root,'src/cli.mjs'),'--dir',directory] } } },null,2));
